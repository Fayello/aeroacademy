const DICT: Record<Lang, Record<string, string>> = { en, fr };

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function readStoredLang(): Lang {
  if (typeof window === "undefined") return "en";
  try {
    const stored = localStorage.getItem("lang");
    if (stored === "fr" || stored === "en") return stored;
    const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language];
    return browserLanguages.some((language) => language.toLowerCase().startsWith("fr")) ? "fr" : "en";
  } catch {
    return "en";
  }
}

function formatValue(template: string, values?: Record<string, string | number>) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? `{${key}}`));
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStoredLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      localStorage.setItem("lang", next);
    } catch {
      /* storage unavailable */
    }
  }, []);

  const t = useCallback(
    (key: string, values?: Record<string, string | number>) =>
      formatValue(DICT[lang][key] ?? en[key] ?? key, values),
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within an I18nProvider");
  return ctx;
}

export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { lang, setLang, t } = useI18n();

  return (
    <div
      className={`flex items-center gap-1 p-1 rounded-lg bg-slate-100 w-fit ${className}`}
      role="group"
      aria-label={t("common.language")}
    >
      {(["en", "fr"] as Lang[]).map((l) => (
        <button
          key={l}
          onClick={() => setLang(l)}
          aria-pressed={lang === l}
          title={l === "en" ? t("common.english") : t("common.french")}
          className={`px-2.5 py-1 rounded-md text-xs font-semibold uppercase tracking-wide transition-colors ${
            lang === l
              ? "bg-[#0F203A] text-white shadow-sm"
              : "text-slate-500 hover:bg-white hover:text-[#0F203A]"
          }`}
        >
          {l}
        </button>
      ))}
    </div>
  );
}
